const Q = 12289;

/* ---------------- BigInt fixed point ---------------- */
let PREC = 1024n;                    // fractional bits
const HALF = () => 1n << (PREC - 1n);
const fp = x => x << PREC;
function fmul(a, b) { return (a * b + HALF()) >> PREC; }
function fdiv(a, b) { return (a << PREC) / b; }
function isqrt(n) {
    if (n < 0n) throw new Error('isqrt neg');
    if (n < 2n) return n;
    let x = 1n << (BigInt(n.toString(2).length) / 2n + 1n);
    for (;;) {
        const y = (x + n / x) >> 1n;
        if (y >= x) break;
        x = y;
    }
    while (x * x > n) x--;
    while ((x + 1n) * (x + 1n) <= n) x++;
    return x;
}
// complex sqrt, principal branch (result has non-negative real part)
function csqrt(ar, ai) {
    const r = isqrt((fmul(ar, ar) + fmul(ai, ai)) << PREC);
    const pr = r + ar, mr = r - ar;
    const re = isqrt(pr > 0n ? (pr << (PREC - 1n)) : 0n);
    const im = isqrt(mr > 0n ? (mr << (PREC - 1n)) : 0n);
    return [re, ai < 0n ? -im : im];
}
// roots of unity table:  Z[L] = e^{2*pi*i/L} for L = 2^k
let ROOT = null;
function buildRoots() {
    const t = {};
    t[2] = [-fp(1n), 0n];
    t[4] = [0n, fp(1n)];
    let L = 4n;
    while (L < 2048n) {
        t[Number(L * 2n)] = csqrt(t[Number(L)][0], t[Number(L)][1]);
        L *= 2n;
    }
    ROOT = t;
}
function getRoot(L) { if (!ROOT) buildRoots(); return ROOT[L]; }

// complex helpers
function cmul(a, b) {
    return [fmul(a[0], b[0]) - fmul(a[1], b[1]), fmul(a[0], b[1]) + fmul(a[1], b[0])];
}
function cdiv(n, d) {
    const den = fmul(d[0], d[0]) + fmul(d[1], d[1]);
    return [fdiv(fmul(n[0], d[0]) + fmul(n[1], d[1]), den),
            fdiv(fmul(n[1], d[0]) - fmul(n[0], d[1]), den)];
}

/* ------------- negacyclic FFT (fixed point) ------------- */
// power table of zeta = e^{i*pi/n}  (order 2n)
function zetaPow(n) {
    const z = getRoot(2 * n);
    const out = [[fp(1n), 0n]];
    for (let j = 1; j < n; j++) out.push(cmul(out[j - 1], z));
    return out;
}
function fwd(a) {              // a: array of BigInt (exact ints) -> values at zeta^(2i+1)
    const n = a.length, zp = zetaPow(n);
    const b = [];
    for (let j = 0; j < n; j++) b.push([fmul(fp(a[j]), zp[j][0]), fmul(fp(a[j]), zp[j][1])]);
    return _fft(b, false);
}
function _fft(a, inv) {
    const n = a.length;
    const b = a.slice();
    let j = 0;
    for (let i = 1; i < n; i++) {
        let bit = n >> 1;
        while (j & bit) { j ^= bit; bit >>= 1; }
        j |= bit;
        if (i < j) { const t = b[i]; b[i] = b[j]; b[j] = t; }
    }
    for (let len = 2; len <= n; len <<= 1) {
        let wl = getRoot(len);
        if (inv) wl = [wl[0], -wl[1]];
        const half = len >> 1;
        for (let i = 0; i < n; i += len) {
            let w = [fp(1n), 0n];
            for (let k = i; k < i + half; k++) {
                const u = b[k], v = cmul(b[k + half], w);
                b[k] = [u[0] + v[0], u[1] + v[1]];
                b[k + half] = [u[0] - v[0], u[1] - v[1]];
                w = cmul(w, wl);
            }
        }
    }
    if (inv) {
        const ni = fdiv(fp(1n), fp(BigInt(n)));
        for (let i = 0; i < n; i++) b[i] = [fmul(b[i][0], ni), fmul(b[i][1], ni)];
    }
    return b;
}
function invf(v) {
    const n = v.length;
    const z = getRoot(2 * n);
    const zi = cdiv([fp(1n), 0n], z);          // zeta^-1
    const zp = [[fp(1n), 0n]];
    for (let j = 1; j < n; j++) zp.push(cmul(zp[j - 1], zi));
    const b = _fft(v, true);
    const out = [];
    for (let j = 0; j < n; j++) {
        const c = cmul(b[j], zp[j]);
        const re = c[0];
        // round to nearest integer
        out.push((re + HALF()) >> PREC);
    }
    return out;
}
function fftMul(a, b) {
    const A = fwd(a), B = fwd(b);
    return invf(A.map((v, i) => cmul(v, B[i])));
}

/* ------------- exact integer ring arithmetic ------------- */
function mulNeg(a, b) {
    const n = a.length;
    const c = new Array(2 * n - 1).fill(0n);
    for (let i = 0; i < n; i++) {
        if (a[i] === 0n) continue;
        for (let j = 0; j < n; j++) {
            if (b[j] === 0n) continue;
            c[i + j] += a[i] * b[j];
        }
    }
    const o = new Array(n).fill(0n);
    for (let i = 0; i < c.length; i++) {
        if (i < n) o[i] += c[i]; else o[i - n] -= c[i];
    }
    return o;
}
const sigma = a => a.map((v, i) => (i & 1) ? -v : v);
function fold(a) {
    const o = [];
    for (let j = 0; j < a.length / 2; j++) o.push(a[2 * j]);
    return o;
}
function lift(a) {
    const o = new Array(a.length * 2).fill(0n);
    for (let j = 0; j < a.length; j++) o[2 * j] = a[j];
    return o;
}
const addp = (a, b) => a.map((v, i) => v + b[i]);
const subp = (a, b) => a.map((v, i) => v - b[i]);

/* ------------------------- tower ------------------------- */
function buildTower(f, g, logn) {
    const lv = [[f.slice(), g.slice()]];
    for (let k = 0; k < logn; k++) {
        const [a, b] = lv[lv.length - 1];
        lv.push([fold(mulNeg(a, sigma(a))), fold(mulNeg(b, sigma(b)))]);
    }
    return lv;
}

/* ------------------------- Babai ------------------------- */
function babai(F, G, f, g) {
    const n = F.length;
    const sf = sigma(f), sg = sigma(g);
    const den = addp(mulNeg(f, sf), mulNeg(g, sg));
    const num = addp(mulNeg(F, sf), mulNeg(G, sg));
    const A = fwd(den), B = fwd(num);
    const w = [];
    for (let i = 0; i < n; i++) w.push(cdiv(B[i], A[i]));
    return invf(w);
}

/* ---------------------- solve NTRU ---------------------- */
function solveNTRU(f, g) {
    const N = f.length;
    const logn = Math.round(Math.log2(N));
    const lv = buildTower(f, g, logn);

    const fd = lv[logn][0], gd = lv[logn][1];
    const rf = fd[0], rg = gd[0];
    // iterative extended gcd
    let or_ = rf, r = rg, os = 1n, s = 0n, ot = 0n, t = 1n;
    while (r !== 0n) {
        const m = or_ / r;
        [or_, r] = [r, or_ - m * r];
        [os, s] = [s, os - m * s];
        [ot, t] = [t, ot - m * t];
    }
    if (or_ < 0n) { or_ = -or_; os = -os; ot = -ot; }
    if (or_ !== 1n) throw new Error('gcd != 1');
    let F = [-BigInt(Q) * ot], G = [BigInt(Q) * os];
    if (rf * G[0] - rg * F[0] !== BigInt(Q)) throw new Error('deepest fail');

    for (let depth = logn - 1; depth >= 0; depth--) {
        const fk = lv[depth][0], gk = lv[depth][1];
        F = mulNeg(sigma(gk), lift(F));
        G = mulNeg(sigma(fk), lift(G));
        let chk = subp(mulNeg(fk, G), mulNeg(gk, F));
        if (chk[0] !== BigInt(Q) || chk.slice(1).some(v => v !== 0n)) throw new Error('lift inv');
        const k = babai(F, G, fk, gk);
        F = subp(F, mulNeg(k, fk));
        G = subp(G, mulNeg(k, gk));
        chk = subp(mulNeg(fk, G), mulNeg(gk, F));
        if (chk[0] !== BigInt(Q) || chk.slice(1).some(v => v !== 0n)) throw new Error('babai inv');
        let mx = 0n;
        for (const v of F) mx = mx > (v > 0n ? v : -v) ? mx : (v > 0n ? v : -v);
        for (const v of G) mx = mx > (v > 0n ? v : -v) ? mx : (v > 0n ? v : -v);

    }
    return [F, G];
}

/* ------------- h = g * f^-1 mod q  (NTT over Z_q) ------------- */
let MODQ = null;
function buildModQ() {
    // primitive root of 12289
    let g0 = 2;
    for (; g0 < Q; g0++) {
        if (pow(g0, (Q - 1) / 2, Q) !== 1 && pow(g0, (Q - 1) / 3, Q) !== 1) break;
    }
    const zeta = pow(g0, (Q - 1) / 1024, Q);
    if (pow(zeta, 512, Q) !== Q - 1) throw new Error('zeta');
    MODQ = { zeta };
}
function pow(a, e, m) {
    let r = 1; a = ((a % m) + m) % m;
    while (e > 0) { if (e & 1) r = r * a % m; a = a * a % m; e >>= 1; }
    return r;
}
function nttMod(a, inv) {
    if (!MODQ) buildModQ();
    const n = a.length, z = MODQ.zeta;
    const b = a.slice();
    if (!inv) for (let j = 0; j < n; j++) b[j] = b[j] * pow(z, j, Q) % Q;
    let jj = 0;
    for (let i = 1; i < n; i++) {
        let bit = n >> 1;
        while (jj & bit) { jj ^= bit; bit >>= 1; }
        jj |= bit;
        if (i < jj) { const t = b[i]; b[i] = b[jj]; b[jj] = t; }
    }
    const omega = pow(z, 2, Q);
    for (let len = 2; len <= n; len <<= 1) {
        let wl = pow(omega, n / len, Q);
        if (inv) wl = pow(wl, Q - 2, Q);
        const half = len >> 1;
        for (let i = 0; i < n; i += len) {
            let w = 1;
            for (let k = i; k < i + half; k++) {
                const u = b[k], v = b[k + half] * w % Q;
                b[k] = (u + v) % Q; b[k + half] = (u - v + Q) % Q;
                w = w * wl % Q;
            }
        }
    }
    if (inv) {
        const ni = pow(n, Q - 2, Q);
        const zi = pow(z, Q - 2, Q);
        for (let j = 0; j < n; j++) b[j] = b[j] * ni % Q * pow(zi, j, Q) % Q;
    }
    return b;
}
function mulMod(a, b) {
    const A = nttMod(a, false), B = nttMod(b, false);
    return nttMod(A.map((v, i) => v * B[i] % Q), true);
}
function invMod(a) {
    const A = nttMod(a, false);
    return nttMod(A.map(v => pow(v, Q - 2, Q)), true);
}
function computeH(f, g) {
    const BQ = BigInt(Q);
    const fn = f.map(v => Number(((v % BQ) + BQ) % BQ));
    const gn = g.map(v => Number(((v % BQ) + BQ) % BQ));
    return mulMod(invMod(fn), gn);
}




  /* ---------------- 公钥编码（modq，14 bits/coeff） ---------------- */
  function modqEncode(x, logn) {
    var n = 1 << logn, u;
    for (u = 0; u < n; u++) if (x[u] < 0 || x[u] >= Q) return null;
    var outLen = ((n * 14) + 7) >> 3;
    var buf = new Uint8Array(outLen);
    var acc = 0, accLen = 0, p = 0;
    for (u = 0; u < n; u++) {
      acc = ((acc << 14) | (x[u] & 0x3FFF)) >>> 0;
      accLen += 14;
      while (accLen >= 8) { accLen -= 8; buf[p++] = (acc >>> accLen) & 0xff; }
    }
    if (accLen > 0) buf[p] = (acc << (8 - accLen)) & 0xff;
    return buf;
  }

  /* ---------------- 正交化范数检查（bnorm，浮点 FFT） ---------------- */
  var LAST_BNORM = 0;
  function bnormOk(f, g, logn) {
    /* 布局同 PQClean：数组长度 n=1<<logn，[0,hn) 实部、[hn,n) 虚部，循环只走 hn */
    var N = 1 << logn, hn = N >> 1, u;
    var a = new Float64Array(N), b = new Float64Array(N), d = new Float64Array(N);
    for (u = 0; u < N; u++) { a[u] = f[u]; b[u] = g[u]; }
    K.FFT(a, logn); K.FFT(b, logn);
    /* d = 1/(|a|^2+|b|^2)，只算前 hn 个（共轭对称） */
    for (u = 0; u < hn; u++) {
      d[u] = 1 / (a[u] * a[u] + a[u + hn] * a[u + hn] + b[u] * b[u] + b[u + hn] * b[u + hn]);
    }
    /* adj + *q + *d */
    for (u = 0; u < hn; u++) {
      a[u + hn] = -a[u + hn] * Q * d[u];
      a[u] = a[u] * Q * d[u];
      b[u + hn] = -b[u + hn] * Q * d[u];
      b[u] = b[u] * Q * d[u];
    }
    K.iFFT(a, logn); K.iFFT(b, logn);
    var s = 0;
    for (u = 0; u < N; u++) { s += a[u] * a[u]; s += b[u] * b[u]; }
    LAST_BNORM = s;
    return s < BNORM_MAX;
  }

  /* ---------------- 高斯采样：seed → f / g ---------------- */
  /* GAUSS 表预拆成高/低 32 位（Number），使比较完全走 Number，
     不再需要每次比较都动用 BigInt。拆分是精确的（BigInt 位运算）。 */
  var GAUSS_HI = GAUSS.map(function (x) { return Number(x >> 32n); });
  var GAUSS_LO = GAUSS.map(function (x) { return Number(x & 0xffffffffn); });

  function makeSampler(nextByte) {
    /* 原实现用 BigInt 拼 u64 并用 BigInt 逐项比较：一次 mkgauss 约 60 次 BigInt 运算，
       而 mkgauss 被调用 n*2*tries 次（512/tries=31 时约 3.2 万次），是最大热点。
       现全程用 Number：读 8 字节拼成两个 32 位半字，比较用 (hi,lo) 字典序。 */
    function u64() {
      var lo = (nextByte() | (nextByte() << 8) | (nextByte() << 16) | (nextByte() << 24)) >>> 0;
      var hi = (nextByte() | (nextByte() << 8) | (nextByte() << 16) | (nextByte() << 24)) >>> 0;
      return [lo, hi];
    }
    return function mkgauss(logn) {
      var g = 1 << (10 - logn), val = 0, i;
      for (i = 0; i < g; i++) {
        var r = u64();
        var neg = (r[1] >>> 31) & 1;
        var rh = r[1] & 0x7fffffff, rl = r[0];
        var f = (rh < GAUSS_HI[0] || (rh === GAUSS_HI[0] && rl < GAUSS_LO[0])) ? 1 : 0, v = 0;
        var r2 = u64();
        var r2h = r2[1] & 0x7fffffff, r2l = r2[0];
        for (var k = 1; k < GAUSS.length; k++) {
          var t = (r2h > GAUSS_HI[k] || (r2h === GAUSS_HI[k] && r2l >= GAUSS_LO[k])) ? 1 : 0;
          if (t && !f) v = k;
          f |= t;
        }
        val += neg ? -v : v;
      }
      return val;
    };
  }

