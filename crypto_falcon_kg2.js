  var DIAG = [];
  function keygen(seed48, logn) {
    DIAG = [];
    if (!shake256) throw new Error('falconShake256 未加载');
    if (!K) throw new Error('FALCON_KG 未加载');
    if (logn !== 9 && logn !== 10) throw new Error('仅支持 Falcon-512 / 1024（logn=9/10）');
    var n = 1 << logn;
    var streamLen = 1 << 18;
    var stream = shake256(seed48, streamLen);
    var spos = 0;
    function nextByte() {
      if (spos >= stream.length) { streamLen <<= 1; stream = shake256(seed48, streamLen); }
      return stream[spos++];
    }
    var mkgauss = makeSampler(nextByte);
    var limfg = 1 << (K.MAX_FG_BITS[logn] - 1);
    var limF = (1 << (K.MAX_FG_BITS_F[logn] - 1)) - 1;
    var tries = 0;

    function smallPoly(mod2Box) {
      var out = new Array(n), u;
      for (u = 0; u < n; u++) for (;;) {
        var s = mkgauss(logn);
        if (s < -127 || s > 127) continue;
        if (u === n - 1) { if ((mod2Box.v ^ (s & 1)) === 0) continue; }
        else mod2Box.v ^= (s & 1);
        out[u] = s; break;
      }
      return out;
    }

    for (;;) {
      tries++;
      if (tries > 64) throw new Error('密钥生成重试超过 64 次（极罕见，请换种子）');
      /* 官方 poly_small_mkgauss 每次进入都 mod2 = 0：f 与 g 各自独立累积，
         不能共用同一个 mod2，否则 g 的末系数奇偶校验判据会错。 */
      var f = smallPoly({ v: 0 });
      var g = smallPoly({ v: 0 });
      var u, ok = true;
      for (u = 0; u < n; u++) {
        if (f[u] >= limfg || f[u] <= -limfg || g[u] >= limfg || g[u] <= -limfg) { ok = false; break; }
      }
      if (!ok) continue;
      var nf = 0, ng = 0;
      for (u = 0; u < n; u++) { nf += f[u] * f[u]; ng += g[u] * g[u]; }
      if (nf + ng >= 16823) { DIAG.push({ t: tries, why: 'R2', n: nf + ng, f: f.slice(0, 8), g: g.slice(0, 8) }); continue; }
      if (!bnormOk(f, g, logn)) { DIAG.push({ t: tries, why: 'R3', b: LAST_BNORM, f: f.slice(0, 8), g: g.slice(0, 8) }); continue; }
      DIAG.push({ t: tries, why: 'pass-bnorm', b: LAST_BNORM, f: f.slice(0, 8), g: g.slice(0, 8) });
      var h = K.compute_public(f, g, logn);
      if (!h) continue;
      var Fb = f.map(function (x) { return BigInt(x); });
      var Gb = g.map(function (x) { return BigInt(x); });
      var sol;
      try { sol = solveNTRU(Fb, Gb); } catch (e) { continue; }
      var F = sol[0], G = sol[1], mx = 0;
      for (u = 0; u < n; u++) {
        mx = Math.max(mx, Math.abs(Number(F[u])), Math.abs(Number(G[u])));
      }
      if (mx > limF) continue;
      var Fs = F.map(Number), Gs = G.map(Number);
      return { f: f, g: g, F: Fs, G: Gs, h: h, tries: tries, maxFG: mx };
    }
  }

