var ZUC_MASK31 = 0x7fffffff;
function zucRol32(x, n) { return (((x << n) | (x >>> (32 - n))) >>> 0); }
function zucL1(X) { return (X ^ zucRol32(X, 2) ^ zucRol32(X, 10) ^ zucRol32(X, 18) ^ zucRol32(X, 24)) >>> 0; }
function zucL2(X) { return (X ^ zucRol32(X, 8) ^ zucRol32(X, 14) ^ zucRol32(X, 22) ^ zucRol32(X, 30)) >>> 0; }
function zucBS(X) {
  return (((ZUC_S0[(X >>> 24) & 0xff] << 24) ^ (ZUC_S1[(X >>> 16) & 0xff] << 16) ^
           (ZUC_S0[(X >>> 8) & 0xff] << 8) ^ ZUC_S1[X & 0xff]) >>> 0);
}
function zucNew(key, iv) {
  if (key.length !== 16) throw new Error('ZUC 密钥需 16 字节');
  if (iv.length !== 16) throw new Error('ZUC 的 IV 需 16 字节');
  var S = new Array(16), i;
  for (i = 0; i < 16; i++) S[i] = ((key[i] << 23) | (ZUC_D[i] << 8) | iv[i]) >>> 0;
  return { S: S, R1: 0, R2: 0 };
}
function zucLfsrWork(st, u) {
  var S = st.S;
  /* ⚠ LFSR 的模数是 2^31 - 1（0x7fffffff），【不是】2^31（0x80000000）。
     我第一版写成了 % 0x80000000，结果全部输出都错但不报错 —— 而且自洽，
     往返加解密照样通过，只有与参考实现比对才暴露。
     另外 S 各项最大 31 位、系数最大 2^21，累加和可达 2^52，
     仍在 double 的 2^53 精确范围内，可以直接用 + 累加后取模。 */
  var v = (S[15] * 0x8000 + S[13] * 0x20000 + S[10] * 0x200000 + S[4] * 0x100000 + S[0] * 0x100 + S[0] + (u || 0)) % 0x7fffffff;
  S.push(v === 0 ? ZUC_MASK31 : v);
  S.shift();
}
function zucF(st, X0, X1, X2) {
  var W = (((X0 ^ st.R1) + st.R2) >>> 0);
  var W1 = ((st.R1 + X1) >>> 0);
  var W2 = (st.R2 ^ X2) >>> 0;
  st.R1 = zucBS(zucL1((((W1 & 0xffff) << 16) ^ (W2 >>> 16)) >>> 0));
  st.R2 = zucBS(zucL2((((W2 & 0xffff) << 16) ^ (W1 >>> 16)) >>> 0));
  return W;
}
function zucInit(key, iv) {
  var st = zucNew(key, iv), S = st.S, i, X0, X1, X2;
  for (i = 0; i < 32; i++) {
    X0 = (((S[15] >>> 15) << 16) | (S[14] & 0xffff)) >>> 0;
    X1 = (((S[11] & 0xffff) << 16) | (S[9] >>> 15)) >>> 0;
    X2 = (((S[7] & 0xffff) << 16) | (S[5] >>> 15)) >>> 0;
    zucLfsrWork(st, zucF(st, X0, X1, X2) >>> 1);
  }
  zucGenerate(st);   /* 首字丢弃，与规范一致 */
  return st;
}
function zucGenerate(st) {
  var S = st.S;
  var X0 = (((S[15] >>> 15) << 16) | (S[14] & 0xffff)) >>> 0;
  var X1 = (((S[11] & 0xffff) << 16) | (S[9] >>> 15)) >>> 0;
  var X2 = (((S[7] & 0xffff) << 16) | (S[5] >>> 15)) >>> 0;
  var X3 = (((S[2] & 0xffff) << 16) | (S[0] >>> 15)) >>> 0;
  var Z = (zucF(st, X0, X1, X2) ^ X3) >>> 0;
  zucLfsrWork(st, 0);
  return Z;
}
function zucKeystream(key, iv, words) {
  var st = zucInit(key, iv), out = new Uint8Array(words * 4), z, i;
  for (i = 0; i < words; i++) {
    z = zucGenerate(st);
    out[i * 4] = (z >>> 24) & 0xff; out[i * 4 + 1] = (z >>> 16) & 0xff;
    out[i * 4 + 2] = (z >>> 8) & 0xff; out[i * 4 + 3] = z & 0xff;
  }
  return out;
}
function zucCrypt(data, key, iv) {
  var n = data.length, words = Math.ceil(n / 4);
  var ks = zucKeystream(key, iv, words), out = new Uint8Array(n), i;
  for (i = 0; i < n; i++) out[i] = data[i] ^ ks[i];
  return out;
}

